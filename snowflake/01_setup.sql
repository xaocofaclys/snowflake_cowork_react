-- =====================================================================
-- 01_setup.sql: roles, warehouse, databases. Run as ACCOUNTADMIN.
-- =====================================================================
USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS COWORK_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

-- End-user role: what each signed-in user's OAuth session runs as.
CREATE ROLE IF NOT EXISTS COWORK_USER;
-- App service role: owns the app-metadata schema, runs background LLM jobs.
CREATE ROLE IF NOT EXISTS COWORK_APP_SERVICE;
GRANT ROLE COWORK_USER TO ROLE SYSADMIN;
GRANT ROLE COWORK_APP_SERVICE TO ROLE SYSADMIN;

GRANT USAGE ON WAREHOUSE COWORK_WH TO ROLE COWORK_USER;
GRANT USAGE ON WAREHOUSE COWORK_WH TO ROLE COWORK_APP_SERVICE;

-- Cortex LLM functions / agents.
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE COWORK_USER;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE COWORK_APP_SERVICE;

-- If your region lacks a model you set in LLM_MODEL, allow cross-region inference:
-- ALTER ACCOUNT SET CORTEX_ENABLED_CROSS_REGION = 'ANY_REGION';

-- App metadata (threads, messages, artifacts, memories, skills, settings).
CREATE DATABASE IF NOT EXISTS COWORK_APP;
CREATE SCHEMA IF NOT EXISTS COWORK_APP.CORE;
GRANT USAGE ON DATABASE COWORK_APP TO ROLE COWORK_APP_SERVICE;
GRANT ALL ON SCHEMA COWORK_APP.CORE TO ROLE COWORK_APP_SERVICE;
GRANT ALL ON FUTURE TABLES IN SCHEMA COWORK_APP.CORE TO ROLE COWORK_APP_SERVICE;

-- Demo data + agents.
CREATE DATABASE IF NOT EXISTS DEV_REACT_COWORK;
CREATE SCHEMA IF NOT EXISTS DEV_REACT_COWORK.TPCH;
CREATE SCHEMA IF NOT EXISTS DEV_REACT_COWORK.ANALYTICS;
CREATE SCHEMA IF NOT EXISTS DEV_REACT_COWORK.AGENTS;
GRANT USAGE ON DATABASE DEV_REACT_COWORK TO ROLE COWORK_USER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE DEV_REACT_COWORK TO ROLE COWORK_USER;

-- Give yourself the end-user role (OAuth blocks ACCOUNTADMIN/SECURITYADMIN by default).
SET me = CURRENT_USER();
GRANT ROLE COWORK_USER TO USER IDENTIFIER($me);
